vclmul module_inst (
    .instr_type_i (tb_instr_type_i),
    .data_vs1_i   (tb_data_vs1_i),
    .data_vs2_i   (tb_data_vs2_i),
    .data_vd_o    (tb_data_vd_o)
);

// Initializes the DUT inputs, sets up waveform dumping, drives the KAT
// vectors through vclmul/vclmulh and reports a single pass/fail verdict.
    task automatic test_sim;
        begin
            int     status;
            bus64_t expected_result;

            $display("*** init_sim");
            tb_instr_type_i <= VCLMUL;
            tb_data_vs1_i   <='0;
            tb_data_vs2_i   <='0;

            $display("*** test_sim");
            status = 0;
            for (int i = 0; i < NUM_KAT_ENTRIES; i++) begin
                tb_data_vs1_i <= kat_i[i][0];
                tb_data_vs2_i <= kat_i[i][1];

                tb_instr_type_i <= VCLMUL;
                #CLK_PERIOD;
                expected_result = kat_o[i][0];
                if (tb_data_vd_o !== expected_result) begin
                    status = 1;
                    `START_RED_PRINT
                    $error("Result incorrect VCLMUL(%h,%h) = %h, output: %h",
                           kat_i[i][0],kat_i[i][1],expected_result,tb_data_vd_o);
                    `END_COLOR_PRINT
                end

                tb_instr_type_i <= VCLMULH;
                #CLK_PERIOD;
                expected_result = kat_o[i][1];
                if (tb_data_vd_o !== expected_result) begin
                    status = 1;
                    `START_RED_PRINT
                    $error("Result incorrect VCLMULH(%h,%h) = %h, output: %h",
                           kat_i[i][0],kat_i[i][1],expected_result,tb_data_vd_o);
                    `END_COLOR_PRINT
                end
            end

            if (status) begin
                `START_RED_PRINT
                $display("TEST FAILED.");
                `END_COLOR_PRINT
            end else begin
                `START_GREEN_PRINT
                $display("TEST PASSED.");
                `END_COLOR_PRINT
            end
        end
    endtask

    initial begin
        $dumpfile("vclmul.vcd");
        $dumpvars(0,module_inst);
        test_sim();
        $finish;
    end


